/**
 * Verifies the two-phase "Next" button on step 2 of the challenge wizard.
 *
 * What this tests:
 *   1. Login as professor.
 *   2. Open the create-challenge wizard at /create.
 *   3. Walk through step 0 (basic info) and step 1 (description).
 *   4. On step 2 (reference solutions):
 *      a. Button is labelled "Next" before save.
 *      b. Clicking it fires the create mutation and shows a green success alert.
 *      c. Button label changes to "Continue to Knowledge Base".
 *      d. Clicking it again advances to step 3 (KB).
 *   5. Verify the professor lands on the KB step and not still on step 2.
 */
import { test, expect } from "@playwright/test";
import { PROFESSOR } from "./helpers/seed";
import { makeShooter } from "./helpers/screenshots";

test.describe("Challenge wizard — two-phase Next on step 2", () => {
  test("save shows success alert, second click advances to KB step", async ({
    page,
  }, testInfo) => {
    const shot = makeShooter(page, testInfo);

    // ---- 1. Login ----
    await page.goto("/auth/login");
    await page.getByLabel(/email/i).fill(PROFESSOR.email);
    await page.getByLabel(/password/i).fill(PROFESSOR.password);
    await page.getByRole("button", { name: /sign in/i }).click();
    await page.waitForURL((url) => !url.pathname.startsWith("/auth/login"), {
      timeout: 30_000,
    });

    // ---- 2. Open the create-challenge wizard ----
    await page.goto("/create");
    // Wait for the wizard to render
    await expect(page.getByText("Problem Title")).toBeVisible({
      timeout: 10_000,
    });

    // ---- 3. Step 0 — fill basic info ----
    await page
      .getByPlaceholder(/quick sort/i)
      .fill("E2E Two-Phase Wizard Test");

    // Difficulty
    await page.getByRole("combobox").first().click();
    await page.getByRole("option").first().click();

    // Select an existing classroom using the second combobox.
    const classroomCombo = page.getByRole("combobox").last();
    await classroomCombo.click();
    await page.getByRole("option").first().click();

    // Advance to step 1
    await page.getByRole("button", { name: "Next", exact: true }).click();

    // ---- 4. Step 1 — description ----
    await expect(page.getByPlaceholder(/markdown/i)).toBeVisible({
      timeout: 5_000,
    });
    await page
      .getByPlaceholder(/markdown/i)
      .fill("Test description generated by E2E.");

    // Advance to step 2
    await page.getByRole("button", { name: "Next", exact: true }).click();

    // ---- 5. Step 2 — reference solutions (first click = save) ----
    await expect(
      page.getByText("Reference Solutions", { exact: true }).first(),
    ).toBeVisible({ timeout: 5_000 });

    // Button should say "Next" before save.
    await expect(
      page.getByRole("button", { name: "Next", exact: true }),
    ).toBeVisible();

    // Click to trigger the create mutation
    await page.getByRole("button", { name: "Next", exact: true }).click();

    // Green success alert must appear — challenge saved, generation started
    await expect(page.getByText(/challenge saved/i)).toBeVisible({
      timeout: 20_000,
    });

    // Button label must have changed to "Continue to Knowledge Base".
    await expect(
      page.getByRole("button", {
        name: "Continue to Knowledge Base",
        exact: true,
      }),
    ).toBeVisible({ timeout: 5_000 });
    await shot("step2-saved-success-alert");

    // ---- 6. Second click — advance to KB step ----
    await page
      .getByRole("button", { name: "Continue to Knowledge Base", exact: true })
      .click();

    // KB step renders a heading or content about "Knowledge Base"
    await expect(page.getByText(/knowledge base/i).first()).toBeVisible({
      timeout: 10_000,
    });

    // The two-phase button must be gone once the KB step opens.
    await expect(
      page.getByRole("button", {
        name: "Continue to Knowledge Base",
        exact: true,
      }),
    ).not.toBeVisible();

    // Capture final state
    await shot("step3-knowledge-base");
  });
});
